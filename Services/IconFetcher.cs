using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Net;
using System.Net.Http;
using System.Threading;
using System.Threading.Tasks;
using MihomoLauncher.Models;

namespace MihomoLauncher.Services
{
    // Auto-icons: each rule with AutoIcon=true gets its tile icon downloaded from the server.
    // The icon is RECOGNISED from the rule's contents (see SlugFor): its name, its programs'
    // exe names, its sites' domains and its blackmatrix7 template — against Data\icons.txt,
    // the index of the icon set on https://byfox.dev/data/mihomolauncher/ico/ (generated by
    // build\gen-icons.ps1 from ico\ + icon-aliases.txt). "Ютуб" with site youtube.com ->
    // .../ico/youtube.png. Nothing recognised -> the old scheme: the name itself, lowercased.
    // Two places, looked up in this order:
    //   Data\ico\<slug>.png      — icons shipped with the build (ours: all_trafic, byfox…); they
    //                              win, the server is never asked about them;
    //   DataUser\ico\<slug>.png  — what was downloaded. In DataUser\ because an update wipes
    //                              Data\ whole: the cache used to go with it, and the startup
    //                              re-download ran in the middle of the first engine reloads and
    //                              failed — tiles came up without icons (YouTube, PAPA2, 2026-11-09).
    // IconPath is pointed at whichever file it is.
    public static class IconFetcher
    {
        private const string BaseUrl = "https://byfox.dev/data/mihomolauncher/ico/";

        // The download cache (survives updates).
        public static string IcoDir => Path.Combine(VersionInfo.DataUserDir, "ico");

        // Shipped with the build — replaced by every update, never written to at runtime.
        public static string ShippedDir => Path.Combine(AppContext.BaseDirectory, "Data", "ico");

        // The icon file for a slug that is already on disk: shipped first, then the cache; "" if none.
        private static string Existing(string slug)
        {
            try
            {
                var shipped = Path.Combine(ShippedDir, slug + ".png");
                if (File.Exists(shipped)) return shipped;
                var cached = Path.Combine(IcoDir, slug + ".png");
                return File.Exists(cached) ? cached : "";
            }
            catch { return ""; }
        }

        private static bool IsShipped(string path)
            => path.StartsWith(ShippedDir + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase);

        private static string IndexPath => Path.Combine(AppContext.BaseDirectory, "Data", "icons.txt");

        private static readonly HttpClient Http = CreateClient();

        private static HttpClient CreateClient()
        {
            try { ServicePointManager.SecurityProtocol |= SecurityProtocolType.Tls12; } catch { }
            var h = new HttpClient { Timeout = TimeSpan.FromSeconds(15) };
            h.DefaultRequestHeaders.UserAgent.TryParseAdd("MihomoLauncher/" + VersionInfo.AppVersion);
            return h;
        }

        // ---------- Recognition ----------

        // icons.txt, loaded once: the icon slugs, "key=slug" aliases and "@domain=slug" domains.
        private sealed class Index
        {
            public readonly HashSet<string> Slugs = new HashSet<string>(StringComparer.Ordinal);
            // Slug with separators dropped ("googlegemini" -> "google-gemini").
            public readonly Dictionary<string, string> Compact = new Dictionary<string, string>(StringComparer.Ordinal);
            public readonly Dictionary<string, string> Aliases = new Dictionary<string, string>(StringComparer.Ordinal);
            public readonly Dictionary<string, string> Domains = new Dictionary<string, string>(StringComparer.Ordinal);
        }

        private static Index _index;
        private static readonly object IndexLock = new object();

        private static Index GetIndex()
        {
            lock (IndexLock)
            {
                if (_index != null) return _index;
                var ix = new Index();
                try
                {
                    if (File.Exists(IndexPath))
                    {
                        foreach (var raw in File.ReadAllLines(IndexPath, System.Text.Encoding.UTF8))
                        {
                            var line = raw.Trim().ToLowerInvariant();
                            if (line.Length == 0 || line[0] == '#') continue;
                            int eq = line.LastIndexOf('=');
                            if (eq < 0)
                            {
                                ix.Slugs.Add(line);
                                var c = CompactKey(line);
                                if (c.Length > 0 && !ix.Compact.ContainsKey(c)) ix.Compact[c] = line;
                                continue;
                            }
                            var key = line.Substring(0, eq).Trim();
                            var slug = line.Substring(eq + 1).Trim();
                            if (key.Length == 0 || slug.Length == 0) continue;
                            if (key[0] == '@') ix.Domains[key.Substring(1).Trim('.')] = slug;
                            else ix.Aliases[NormKey(key)] = slug;
                        }
                    }
                }
                catch { }
                _index = ix;
                return ix;
            }
        }

        private static string NormKey(string s)
        {
            if (string.IsNullOrWhiteSpace(s)) return "";
            return string.Join(" ", s.Trim().ToLowerInvariant()
                .Split(new[] { ' ', '\t', '_' }, StringSplitOptions.RemoveEmptyEntries));
        }

        private static string CompactKey(string s) =>
            new string((s ?? "").ToLowerInvariant().Where(char.IsLetterOrDigit).ToArray());

        // A name / exe name / domain label -> icon slug, or "".
        private static string Lookup(Index ix, string key)
        {
            key = NormKey(key);
            if (key.Length == 0) return "";
            if (ix.Aliases.TryGetValue(key, out var a)) return a;
            if (ix.Slugs.Contains(key)) return key;
            var dashed = key.Replace(' ', '-');
            if (ix.Slugs.Contains(dashed)) return dashed;
            var c = CompactKey(key);
            if (c.Length >= 3 && ix.Compact.TryGetValue(c, out var s)) return s;
            return "";
        }

        // Domain labels that say nothing about the service ("web.telegram.org" -> skip "web").
        private static readonly HashSet<string> GenericLabels = new HashSet<string>(StringComparer.Ordinal)
        {
            "www", "web", "app", "apps", "api", "m", "mobile", "chat", "mail", "cdn", "static",
            "login", "account", "accounts", "auth", "my", "en", "ru", "co", "com", "net", "org",
            "open", "beta", "dev",
        };

        // A host ("chat.deepseek.com") -> icon slug: first the @domain list (longest suffix
        // wins, so "music.youtube.com" beats "youtube.com"), then each meaningful label from
        // the right, TLD excluded ("deepseek").
        private static string LookupHost(Index ix, string host)
        {
            host = (host ?? "").Trim().Trim('.').ToLowerInvariant();
            if (host.StartsWith("*.")) host = host.Substring(2);
            if (host.Length == 0) return "";
            for (var h = host; h.Length > 0;)
            {
                if (ix.Domains.TryGetValue(h, out var d)) return d;
                int dot = h.IndexOf('.');
                if (dot < 0) break;
                h = h.Substring(dot + 1);
            }
            var labels = host.Split('.');
            for (int i = labels.Length - 2; i >= 0; i--)
            {
                if (labels[i].Length < 2 || GenericLabels.Contains(labels[i])) continue;
                var s = Lookup(ix, labels[i]);
                if (s.Length > 0) return s;
            }
            return "";
        }

        private static string HostOf(string url)
        {
            if (string.IsNullOrWhiteSpace(url)) return "";
            var u = url.Trim();
            if (!u.Contains("://")) u = "https://" + u;
            try { return new Uri(u).Host; } catch { return ""; }
        }

        // The icon slug for a rule, recognised from everything the rule contains. Order: the
        // exact name (what the person typed wins), the programs, the sites, the templates'
        // names and domains, then single words of the name. "" when nothing is recognised.
        public static string Recognise(AppEntry app)
        {
            if (app == null) return "";
            var ix = GetIndex();
            if (ix.Slugs.Count == 0) return "";

            var s = Lookup(ix, app.Name);
            if (s.Length > 0) return s;

            foreach (var p in app.Programs ?? new List<RuleProgram>())
            {
                if (p == null) continue;
                var exe = "";
                try { exe = Path.GetFileNameWithoutExtension(p.Path ?? ""); } catch { }
                s = Lookup(ix, exe);
                if (s.Length == 0) s = Lookup(ix, p.Name);
                if (s.Length > 0) return s;
            }

            var sites = (app.Sites ?? new List<RuleSite>()).Where(x => x != null).ToList();
            foreach (var site in sites)
            {
                s = LookupHost(ix, HostOf(site.Url));
                if (s.Length > 0) return s;
            }
            s = LookupHost(ix, HostOf(app.CheckUrl));
            if (s.Length > 0) return s;

            foreach (var site in sites)
            {
                // Template ".../YouTube/YouTube.yaml" -> "youtube" (Apple_Classical.yaml -> "apple").
                if (!site.HasRuleList) continue;
                var tpl = BlackMatrixCatalog.NameForUrl(site.ClashRuleUrl);
                s = Lookup(ix, tpl);
                if (s.Length > 0) return s;
            }
            foreach (var site in sites)
            {
                foreach (var item in (site.RuleItems ?? new List<string>()).Take(200))
                {
                    var parts = (item ?? "").Split(',');
                    if (parts.Length < 2) continue;
                    var type = parts[0].Trim().ToUpperInvariant();
                    if (type != "DOMAIN" && type != "DOMAIN-SUFFIX") continue;
                    s = LookupHost(ix, parts[1]);
                    if (s.Length > 0) return s;
                }
            }

            foreach (var word in (app.Name ?? "").Split(new[] { ' ', '-', '_', '.', '(', ')' }, StringSplitOptions.RemoveEmptyEntries))
            {
                if (word.Length < 3) continue;
                s = Lookup(ix, word);
                if (s.Length > 0) return s;
            }
            return "";
        }

        // Server-side icon file name: the recognised icon, else the rule name as-is (the old
        // scheme, kept so icons uploaded by name still work): lowercased, spaces PRESERVED.
        public static string SlugFor(AppEntry app)
        {
            var s = Recognise(app);
            return s.Length > 0 ? s : Slugify(app?.Name);
        }

        // The rule name as a file name: lowercased, with spaces PRESERVED (collapsed to single
        // spaces). "ChatGPT" -> "chatgpt", "Мозила Фаирфокс" -> "мозила фаирфокс" (-> request
        // .../ico/мозила%20фаирфокс.png). Drops only characters illegal in a Windows filename.
        // Empty if nothing usable remains.
        public static string Slugify(string name)
        {
            if (string.IsNullOrWhiteSpace(name)) return "";
            var invalid = new HashSet<char>(Path.GetInvalidFileNameChars());
            var sb = new System.Text.StringBuilder();
            bool lastSpace = false;
            foreach (var ch in name.Trim().ToLowerInvariant())
            {
                if (char.IsWhiteSpace(ch))
                {
                    if (sb.Length > 0 && !lastSpace) { sb.Append(' '); lastSpace = true; }
                    continue;
                }
                if (invalid.Contains(ch)) continue;
                sb.Append(ch);
                lastSpace = false;
            }
            return sb.ToString().Trim();
        }

        // ---------- Download ----------

        // Download the icon for `app` from the server. Returns the local file path if it now
        // exists (freshly downloaded or already cached), or "" if there is no such icon on the
        // server / the download failed. `force` re-downloads even if cached.
        public static async Task<string> TryFetchAsync(AppEntry app, bool force, CancellationToken ct = default)
        {
            var slug = SlugFor(app);
            if (slug.Length == 0) return "";
            var dest = Path.Combine(IcoDir, slug + ".png");

            var have = Existing(slug);
            if (!force && have.Length > 0) return have;
            if (have.Length > 0 && IsShipped(have)) return have;   // shipped icons win, even on a forced refresh

            try
            {
                Directory.CreateDirectory(IcoDir);
                // Spaces (and any non-ASCII) must be percent-encoded for the URL; the cache
                // filename keeps the readable slug (spaces are valid in Windows filenames).
                var url = BaseUrl + Uri.EscapeDataString(slug) + ".png";
                using (var resp = await Http.GetAsync(url, HttpCompletionOption.ResponseHeadersRead, ct).ConfigureAwait(false))
                {
                    if (!resp.IsSuccessStatusCode)
                    {
                        // 404 = the set simply has no such icon (the tile shows the program's own).
                        if ((int)resp.StatusCode != 404) NoteFailure(slug, "HTTP " + (int)resp.StatusCode);
                        return Existing(slug);
                    }
                    var bytes = await resp.Content.ReadAsByteArrayAsync().ConfigureAwait(false);
                    if (bytes == null || bytes.Length == 0) return Existing(slug);

                    var tmp = dest + ".tmp";
                    File.WriteAllBytes(tmp, bytes);
                    if (File.Exists(dest)) File.Delete(dest);
                    File.Move(tmp, dest);
                    return dest;
                }
            }
            catch (Exception ex)
            {
                // Offline / IO — keep whatever was cached before (may be nothing). Said once per
                // icon in app.log: a tile without its icon used to leave no trace at all.
                NoteFailure(slug, (ex.InnerException ?? ex).Message);
                return Existing(slug);
            }
        }

        private static readonly HashSet<string> _failLogged = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        private static void NoteFailure(string slug, string why)
        {
            lock (_failLogged)
                if (!_failLogged.Add(slug)) return;
            Log.Info("Иконка «" + slug + "» не скачалась с byfox.dev: " + why + " — попробую ещё раз позже.");
        }

        // Some AutoIcon rule still has no icon file — worth another try.
        public static bool AnyMissing(IEnumerable<AppEntry> apps)
        {
            try
            {
                return (apps ?? Enumerable.Empty<AppEntry>()).Any(a => a != null && a.AutoIcon && !a.IsAllTraffic
                    && SlugFor(a).Length > 0 && Existing(SlugFor(a)).Length == 0);
            }
            catch { return false; }
        }

        // Startup pass: for every AutoIcon entry make sure its icon is on disk and IconPath points
        // at it. Downloads any that are missing. Returns true if any entry's IconPath changed
        // (caller should save).
        // checkServer=false: only fill in what's missing (the periodic retry), no HEAD per icon.
        public static async Task<bool> EnsureAsync(IEnumerable<AppEntry> apps, CancellationToken ct = default, bool checkServer = true)
        {
            if (apps == null) return false;
            bool changed = false;
            foreach (var app in apps.ToList())
            {
                if (app == null || !app.AutoIcon) continue;
                var slug = SlugFor(app);
                if (slug.Length == 0) continue;
                var dest = Existing(slug);

                // Missing locally → try to (re)download. Present → just make sure IconPath
                // points at the current location (BaseDirectory can move across installs).
                if (dest.Length == 0)
                {
                    dest = await TryFetchAsync(app, force: false, ct).ConfigureAwait(false);
                    if (string.IsNullOrEmpty(dest)) continue;   // nothing on server (yet)
                }
                else if (checkServer && !IsShipped(dest) && await ServerDiffersAsync(slug, dest, ct).ConfigureAwait(false))
                {
                    // The icon was replaced on the server — the cache would show the old one forever.
                    await TryFetchAsync(app, force: true, ct).ConfigureAwait(false);
                    changed = true;   // same path, new picture: the tiles must be rebuilt
                }
                if (!string.Equals(app.IconPath, dest, StringComparison.OrdinalIgnoreCase))
                {
                    app.IconPath = dest;
                    changed = true;
                }
            }
            return changed;
        }

        // ---------- Site icons (favicon) ----------
        //
        // A rule made only of sites, whose name the icon set doesn't know, had a blank glyph for a
        // tile. The site's own icon is the next best thing: fetched once into DataUser\ico\site\
        // and kept. Tried in order: what the page itself names (apple-touch-icon — usually 180 px,
        // then <link rel=icon>, biggest first), /apple-touch-icon.png, /favicon.ico. SVG is
        // skipped (WPF can't draw it). Each host is tried once per launcher run.

        public static string SiteIconDir => Path.Combine(IcoDir, "site");

        public static string SiteIconFile(string host)
        {
            if (string.IsNullOrWhiteSpace(host)) return "";
            try
            {
                foreach (var ext in new[] { ".png", ".ico", ".jpg" })
                {
                    var f = Path.Combine(SiteIconDir, host.ToLowerInvariant() + ext);
                    if (File.Exists(f)) return f;
                }
            }
            catch { }
            return "";
        }

        private static readonly HashSet<string> _siteTried = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        // The host a rule's tile would show: the launching site, any site, else the check address.
        public static string SiteHostFor(AppEntry app)
        {
            if (app == null) return "";
            var sites = (app.Sites ?? new List<RuleSite>()).Where(s => s != null && !string.IsNullOrWhiteSpace(s.Url)).ToList();
            var site = sites.FirstOrDefault(s => s.Launch) ?? sites.FirstOrDefault();
            var host = site != null ? HostOf(site.Url) : HostOf(app.CheckUrl);
            return host ?? "";
        }

        // True when a new icon file appeared (the caller redraws the tiles).
        public static async Task<bool> FetchSiteIconAsync(string host, CancellationToken ct = default)
        {
            if (string.IsNullOrWhiteSpace(host) || SiteIconFile(host).Length > 0) return false;
            lock (_siteTried) if (!_siteTried.Add(host)) return false;

            var candidates = new List<string>();
            try { candidates.AddRange(await IconLinksFromPageAsync(host, ct).ConfigureAwait(false)); } catch { }
            candidates.Add("https://" + host + "/apple-touch-icon.png");
            candidates.Add("https://" + host + "/favicon.ico");

            foreach (var url in candidates.Distinct(StringComparer.OrdinalIgnoreCase))
            {
                try
                {
                    using (var req = new HttpRequestMessage(HttpMethod.Get, url))
                    {
                        req.Headers.TryAddWithoutValidation("User-Agent", BrowserUa);
                        using (var resp = await Http.SendAsync(req, ct).ConfigureAwait(false))
                        {
                            if (!resp.IsSuccessStatusCode) continue;
                            var bytes = await resp.Content.ReadAsByteArrayAsync().ConfigureAwait(false);
                            var ext = ImageExt(bytes);
                            if (ext == null) continue;   // an HTML error page, an SVG, nothing
                            Directory.CreateDirectory(SiteIconDir);
                            var dest = Path.Combine(SiteIconDir, host.ToLowerInvariant() + ext);
                            File.WriteAllBytes(dest + ".tmp", bytes);
                            if (File.Exists(dest)) File.Delete(dest);
                            File.Move(dest + ".tmp", dest);
                            return true;
                        }
                    }
                }
                catch (OperationCanceledException) { return false; }
                catch { }
            }
            return false;
        }

        private const string BrowserUa =
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";

        // <link rel="apple-touch-icon" / "icon" href=…> of the home page, best first.
        private static async Task<List<string>> IconLinksFromPageAsync(string host, CancellationToken ct)
        {
            var result = new List<string>();
            var baseUri = new Uri("https://" + host + "/");
            string html;
            using (var req = new HttpRequestMessage(HttpMethod.Get, baseUri))
            {
                req.Headers.TryAddWithoutValidation("User-Agent", BrowserUa);
                using (var resp = await Http.SendAsync(req, ct).ConfigureAwait(false))
                {
                    if (!resp.IsSuccessStatusCode) return result;
                    html = await resp.Content.ReadAsStringAsync().ConfigureAwait(false);
                    baseUri = resp.RequestMessage?.RequestUri ?? baseUri;   // after redirects
                }
            }
            if (html.Length > 400000) html = html.Substring(0, 400000);

            var found = new List<Tuple<int, string>>();
            foreach (System.Text.RegularExpressions.Match m in System.Text.RegularExpressions.Regex.Matches(
                         html, "<link\\b[^>]*>", System.Text.RegularExpressions.RegexOptions.IgnoreCase))
            {
                var tag = m.Value;
                var rel = Attr(tag, "rel").ToLowerInvariant();
                if (!rel.Contains("icon")) continue;
                var href = Attr(tag, "href");
                if (href.Length == 0 || href.StartsWith("data:", StringComparison.OrdinalIgnoreCase)) continue;
                if (href.EndsWith(".svg", StringComparison.OrdinalIgnoreCase) || Attr(tag, "type").Contains("svg")) continue;
                int size = 0;
                var sizes = System.Text.RegularExpressions.Regex.Match(Attr(tag, "sizes"), "(\\d+)");
                if (sizes.Success) int.TryParse(sizes.Groups[1].Value, out size);
                if (rel.Contains("apple-touch-icon") && size == 0) size = 180;
                Uri abs;
                if (Uri.TryCreate(baseUri, System.Net.WebUtility.HtmlDecode(href), out abs)) found.Add(Tuple.Create(size, abs.ToString()));
            }
            // Biggest first, but not absurd ones (a 1024-px PWA icon is fine too — scaled down).
            result.AddRange(found.OrderByDescending(t => t.Item1).Select(t => t.Item2));
            return result;
        }

        private static string Attr(string tag, string name)
        {
            var m = System.Text.RegularExpressions.Regex.Match(tag,
                "\\b" + name + "\\s*=\\s*(\"([^\"]*)\"|'([^']*)'|([^\\s>]+))",
                System.Text.RegularExpressions.RegexOptions.IgnoreCase);
            if (!m.Success) return "";
            return m.Groups[2].Success ? m.Groups[2].Value : m.Groups[3].Success ? m.Groups[3].Value : m.Groups[4].Value;
        }

        // By content, not by the URL: servers happily send HTML with a 200.
        private static string ImageExt(byte[] b)
        {
            if (b == null || b.Length < 8) return null;
            if (b[0] == 0x89 && b[1] == 0x50 && b[2] == 0x4E && b[3] == 0x47) return ".png";
            if (b[0] == 0x00 && b[1] == 0x00 && b[2] == 0x01 && b[3] == 0x00) return ".ico";
            if (b[0] == 0xFF && b[1] == 0xD8) return ".jpg";
            return null;
        }

        // A HEAD request: does the server's file differ in size from the cached one? Quiet —
        // offline or no answer means "keep what we have".
        private static async Task<bool> ServerDiffersAsync(string slug, string dest, CancellationToken ct)
        {
            try
            {
                var url = BaseUrl + Uri.EscapeDataString(slug) + ".png";
                using (var req = new HttpRequestMessage(HttpMethod.Head, url))
                using (var resp = await Http.SendAsync(req, ct).ConfigureAwait(false))
                {
                    if (!resp.IsSuccessStatusCode) return false;
                    var len = resp.Content.Headers.ContentLength;
                    return len.HasValue && len.Value > 0 && len.Value != new FileInfo(dest).Length;
                }
            }
            catch { return false; }
        }
    }
