using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Net;
using System.Net.Http;
using System.Threading;
using System.Threading.Tasks;
using MihomoLauncher.Models;

namespace MihomoLauncher.Services
{
    // Auto-icons: each rule with AutoIcon=true gets its tile icon downloaded from the server.
    // The icon is RECOGNISED from the rule's contents (see SlugFor): its name, its programs'
    // exe names, its sites' domains and its blackmatrix7 template — against Data\icons.txt,
    // the index of the icon set on https://byfox.dev/data/mihomolauncher/ico/ (generated by
    // build\gen-icons.ps1 from ico_web\ + icon-aliases.txt). "Ютуб" with site youtube.com ->
    // .../ico/youtube.png. Nothing recognised -> the old scheme: the name itself, lowercased.
    // Cached under <exe>\Data\ico\<slug>.png and IconPath is pointed at that file. The cache
    // lives in Data\ (wiped by a launcher update), so we re-ensure it on every startup — the
    // AutoIcon flag in the saved config survives updates.
    public static class IconFetcher
    {
        private const string BaseUrl = "https://byfox.dev/data/mihomolauncher/ico/";

        // Sits next to the exe under Data\ico (Release layout). In Debug it's created under
        // bin\Debug\net481\Data\ico — same scheme as GeoIpService.MaxmindDir.
        public static string IcoDir => Path.Combine(AppContext.BaseDirectory, "Data", "ico");

        private static string IndexPath => Path.Combine(AppContext.BaseDirectory, "Data", "icons.txt");

        private static readonly HttpClient Http = CreateClient();

        private static HttpClient CreateClient()
        {
            try { ServicePointManager.SecurityProtocol |= SecurityProtocolType.Tls12; } catch { }
            var h = new HttpClient { Timeout = TimeSpan.FromSeconds(15) };
            h.DefaultRequestHeaders.UserAgent.TryParseAdd("MihomoLauncher/" + VersionInfo.AppVersion);
            return h;
        }

        // ---------- Recognition ----------

        // icons.txt, loaded once: the icon slugs, "key=slug" aliases and "@domain=slug" domains.
        private sealed class Index
        {
            public readonly HashSet<string> Slugs = new HashSet<string>(StringComparer.Ordinal);
            // Slug with separators dropped ("googlegemini" -> "google-gemini").
            public readonly Dictionary<string, string> Compact = new Dictionary<string, string>(StringComparer.Ordinal);
            public readonly Dictionary<string, string> Aliases = new Dictionary<string, string>(StringComparer.Ordinal);
            public readonly Dictionary<string, string> Domains = new Dictionary<string, string>(StringComparer.Ordinal);
        }

        private static Index _index;
        private static readonly object IndexLock = new object();

        private static Index GetIndex()
        {
            lock (IndexLock)
            {
                if (_index != null) return _index;
                var ix = new Index();
                try
                {
                    if (File.Exists(IndexPath))
                    {
                        foreach (var raw in File.ReadAllLines(IndexPath, System.Text.Encoding.UTF8))
                        {
                            var line = raw.Trim().ToLowerInvariant();
                            if (line.Length == 0 || line[0] == '#') continue;
                            int eq = line.LastIndexOf('=');
                            if (eq < 0)
                            {
                                ix.Slugs.Add(line);
                                var c = CompactKey(line);
                                if (c.Length > 0 && !ix.Compact.ContainsKey(c)) ix.Compact[c] = line;
                                continue;
                            }
                            var key = line.Substring(0, eq).Trim();
                            var slug = line.Substring(eq + 1).Trim();
                            if (key.Length == 0 || slug.Length == 0) continue;
                            if (key[0] == '@') ix.Domains[key.Substring(1).Trim('.')] = slug;
                            else ix.Aliases[NormKey(key)] = slug;
                        }
                    }
                }
                catch { }
                _index = ix;
                return ix;
            }
        }

        private static string NormKey(string s)
        {
            if (string.IsNullOrWhiteSpace(s)) return "";
            return string.Join(" ", s.Trim().ToLowerInvariant()
                .Split(new[] { ' ', '\t', '_' }, StringSplitOptions.RemoveEmptyEntries));
        }

        private static string CompactKey(string s) =>
            new string((s ?? "").ToLowerInvariant().Where(char.IsLetterOrDigit).ToArray());

        // A name / exe name / domain label -> icon slug, or "".
        private static string Lookup(Index ix, string key)
        {
            key = NormKey(key);
            if (key.Length == 0) return "";
            if (ix.Aliases.TryGetValue(key, out var a)) return a;
            if (ix.Slugs.Contains(key)) return key;
            var dashed = key.Replace(' ', '-');
            if (ix.Slugs.Contains(dashed)) return dashed;
            var c = CompactKey(key);
            if (c.Length >= 3 && ix.Compact.TryGetValue(c, out var s)) return s;
            return "";
        }

        // Domain labels that say nothing about the service ("web.telegram.org" -> skip "web").
        private static readonly HashSet<string> GenericLabels = new HashSet<string>(StringComparer.Ordinal)
        {
            "www", "web", "app", "apps", "api", "m", "mobile", "chat", "mail", "cdn", "static",
            "login", "account", "accounts", "auth", "my", "en", "ru", "co", "com", "net", "org",
            "open", "beta", "dev",
        };

        // A host ("chat.deepseek.com") -> icon slug: first the @domain list (longest suffix
        // wins, so "music.youtube.com" beats "youtube.com"), then each meaningful label from
        // the right, TLD excluded ("deepseek").
        private static string LookupHost(Index ix, string host)
        {
            host = (host ?? "").Trim().Trim('.').ToLowerInvariant();
            if (host.StartsWith("*.")) host = host.Substring(2);
            if (host.Length == 0) return "";
            for (var h = host; h.Length > 0;)
            {
                if (ix.Domains.TryGetValue(h, out var d)) return d;
                int dot = h.IndexOf('.');
                if (dot < 0) break;
                h = h.Substring(dot + 1);
            }
            var labels = host.Split('.');
            for (int i = labels.Length - 2; i >= 0; i--)
            {
                if (labels[i].Length < 2 || GenericLabels.Contains(labels[i])) continue;
                var s = Lookup(ix, labels[i]);
                if (s.Length > 0) return s;
            }
            return "";
        }

        private static string HostOf(string url)
        {
            if (string.IsNullOrWhiteSpace(url)) return "";
            var u = url.Trim();
            if (!u.Contains("://")) u = "https://" + u;
            try { return new Uri(u).Host; } catch { return ""; }
        }

        // The icon slug for a rule, recognised from everything the rule contains. Order: the
        // exact name (what the person typed wins), the programs, the sites, the templates'
        // names and domains, then single words of the name. "" when nothing is recognised.
        public static string Recognise(AppEntry app)
        {
            if (app == null) return "";
            var ix = GetIndex();
            if (ix.Slugs.Count == 0) return "";

            var s = Lookup(ix, app.Name);
            if (s.Length > 0) return s;

            foreach (var p in app.Programs ?? new List<RuleProgram>())
            {
                if (p == null) continue;
                var exe = "";
                try { exe = Path.GetFileNameWithoutExtension(p.Path ?? ""); } catch { }
                s = Lookup(ix, exe);
                if (s.Length == 0) s = Lookup(ix, p.Name);
                if (s.Length > 0) return s;
            }

            var sites = (app.Sites ?? new List<RuleSite>()).Where(x => x != null).ToList();
            foreach (var site in sites)
            {
                s = LookupHost(ix, HostOf(site.Url));
                if (s.Length > 0) return s;
            }
            s = LookupHost(ix, HostOf(app.CheckUrl));
            if (s.Length > 0) return s;

            foreach (var site in sites)
            {
                // blackmatrix7 template ".../YouTube/YouTube.yaml" -> "youtube".
                if (!site.HasRuleList) continue;
                var tpl = "";
                try { tpl = Path.GetFileNameWithoutExtension(new Uri(site.ClashRuleUrl).AbsolutePath); } catch { }
                s = Lookup(ix, tpl);
                if (s.Length > 0) return s;
            }
            foreach (var site in sites)
            {
                foreach (var item in (site.RuleItems ?? new List<string>()).Take(200))
                {
                    var parts = (item ?? "").Split(',');
                    if (parts.Length < 2) continue;
                    var type = parts[0].Trim().ToUpperInvariant();
                    if (type != "DOMAIN" && type != "DOMAIN-SUFFIX") continue;
                    s = LookupHost(ix, parts[1]);
                    if (s.Length > 0) return s;
                }
            }

            foreach (var word in (app.Name ?? "").Split(new[] { ' ', '-', '_', '.', '(', ')' }, StringSplitOptions.RemoveEmptyEntries))
            {
                if (word.Length < 3) continue;
                s = Lookup(ix, word);
                if (s.Length > 0) return s;
            }
            return "";
        }

        // Server-side icon file name: the recognised icon, else the rule name as-is (the old
        // scheme, kept so icons uploaded by name still work): lowercased, spaces PRESERVED.
        public static string SlugFor(AppEntry app)
        {
            var s = Recognise(app);
            return s.Length > 0 ? s : Slugify(app?.Name);
        }

        // The rule name as a file name: lowercased, with spaces PRESERVED (collapsed to single
        // spaces). "ChatGPT" -> "chatgpt", "Мозила Фаирфокс" -> "мозила фаирфокс" (-> request
        // .../ico/мозила%20фаирфокс.png). Drops only characters illegal in a Windows filename.
        // Empty if nothing usable remains.
        public static string Slugify(string name)
        {
            if (string.IsNullOrWhiteSpace(name)) return "";
            var invalid = new HashSet<char>(Path.GetInvalidFileNameChars());
            var sb = new System.Text.StringBuilder();
            bool lastSpace = false;
            foreach (var ch in name.Trim().ToLowerInvariant())
            {
                if (char.IsWhiteSpace(ch))
                {
                    if (sb.Length > 0 && !lastSpace) { sb.Append(' '); lastSpace = true; }
                    continue;
                }
                if (invalid.Contains(ch)) continue;
                sb.Append(ch);
                lastSpace = false;
            }
            return sb.ToString().Trim();
        }

        // ---------- Download ----------

        // Download the icon for `app` from the server. Returns the local file path if it now
        // exists (freshly downloaded or already cached), or "" if there is no such icon on the
        // server / the download failed. `force` re-downloads even if cached.
        public static async Task<string> TryFetchAsync(AppEntry app, bool force, CancellationToken ct = default)
        {
            var slug = SlugFor(app);
            if (slug.Length == 0) return "";
            var dest = Path.Combine(IcoDir, slug + ".png");

            if (!force && File.Exists(dest)) return dest;

            try
            {
                Directory.CreateDirectory(IcoDir);
                // Spaces (and any non-ASCII) must be percent-encoded for the URL; the cache
                // filename keeps the readable slug (spaces are valid in Windows filenames).
                var url = BaseUrl + Uri.EscapeDataString(slug) + ".png";
                using (var resp = await Http.GetAsync(url, HttpCompletionOption.ResponseHeadersRead, ct).ConfigureAwait(false))
                {
                    if (!resp.IsSuccessStatusCode) return File.Exists(dest) ? dest : "";
                    var bytes = await resp.Content.ReadAsByteArrayAsync().ConfigureAwait(false);
                    if (bytes == null || bytes.Length == 0) return File.Exists(dest) ? dest : "";

                    var tmp = dest + ".tmp";
                    File.WriteAllBytes(tmp, bytes);
                    if (File.Exists(dest)) File.Delete(dest);
                    File.Move(tmp, dest);
                    return dest;
                }
            }
            catch
            {
                // Offline / 404 / IO — keep whatever was cached before (may be nothing).
                return File.Exists(dest) ? dest : "";
            }
        }

        // Startup pass: for every AutoIcon entry make sure its cached icon is present and
        // IconPath points at it. Re-downloads any that are missing (e.g. after an update
        // wiped Data\ico). Returns true if any entry's IconPath changed (caller should save).
        public static async Task<bool> EnsureAsync(IEnumerable<AppEntry> apps, CancellationToken ct = default)
        {
            if (apps == null) return false;
            bool changed = false;
            foreach (var app in apps.ToList())
            {
                if (app == null || !app.AutoIcon) continue;
                var slug = SlugFor(app);
                if (slug.Length == 0) continue;
                var dest = Path.Combine(IcoDir, slug + ".png");

                // Missing locally → try to (re)download. Present → just make sure IconPath
                // points at the current location (BaseDirectory can move across installs).
                if (!File.Exists(dest))
                {
                    var got = await TryFetchAsync(app, force: false, ct).ConfigureAwait(false);
                    if (string.IsNullOrEmpty(got)) continue;   // nothing on server (yet)
                }
                else if (await ServerDiffersAsync(slug, dest, ct).ConfigureAwait(false))
                {
                    // The icon was replaced on the server — the cache would show the old one forever.
                    await TryFetchAsync(app, force: true, ct).ConfigureAwait(false);
                    changed = true;   // same path, new picture: the tiles must be rebuilt
                }
                if (!string.Equals(app.IconPath, dest, StringComparison.OrdinalIgnoreCase))
                {
                    app.IconPath = dest;
                    changed = true;
                }
            }
            return changed;
        }

        // A HEAD request: does the server's file differ in size from the cached one? Quiet —
        // offline or no answer means "keep what we have".
        private static async Task<bool> ServerDiffersAsync(string slug, string dest, CancellationToken ct)
        {
            try
            {
                var url = BaseUrl + Uri.EscapeDataString(slug) + ".png";
                using (var req = new HttpRequestMessage(HttpMethod.Head, url))
                using (var resp = await Http.SendAsync(req, ct).ConfigureAwait(false))
                {
                    if (!resp.IsSuccessStatusCode) return false;
                    var len = resp.Content.Headers.ContentLength;
                    return len.HasValue && len.Value > 0 && len.Value != new FileInfo(dest).Length;
                }
            }
            catch { return false; }
        }
    }
}
